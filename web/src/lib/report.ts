import type { ResumeAnalysis } from "./types";

export function downloadReport(analysis: ResumeAnalysis) {
  const date = new Date(analysis.date).toLocaleDateString("en-US", {
    month: "long",
    day: "numeric",
    year: "numeric",
  });

  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>ResumeAI — ${escapeHtml(analysis.filename)}</title>
<style>
  :root { color-scheme: light; }
  * { box-sizing: border-box; margin: 0; padding: 0; }
  body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", ui-sans-serif, system-ui, sans-serif; background: #eceef4; color: #101117; padding: 48px 24px; line-height: 1.6; }
  .sheet { max-width: 720px; margin: 0 auto; background: #f6f7fb; border-radius: 24px; padding: 48px; box-shadow: 0 24px 60px rgba(20,22,36,0.18); }
  .brand { display: flex; align-items: center; gap: 10px; font-weight: 700; letter-spacing: -0.02em; font-size: 18px; }
  .brand b { color: #4f46e5; }
  h1 { font-size: 30px; letter-spacing: -0.03em; margin: 28px 0 6px; }
  .meta { color: #767a88; font-size: 13px; }
  .score { display: inline-block; margin: 24px 0; padding: 18px 28px; border-radius: 20px; background: linear-gradient(135deg, #0e9f6e, #4f46e5); color: #fff; font-size: 44px; font-weight: 800; }
  .score span { font-size: 15px; font-weight: 600; opacity: 0.85; }
  h2 { font-size: 16px; letter-spacing: -0.01em; margin: 32px 0 14px; padding-top: 22px; border-top: 1px solid rgba(16,17,23,0.08); }
  ul { list-style: none; }
  li { padding: 10px 14px; background: #eceef4; border-radius: 12px; margin-bottom: 8px; font-size: 14px; }
  li b { display: block; font-size: 13px; }
  .pill { display: inline-block; margin: 0 6px 6px 0; padding: 5px 12px; background: #eceef4; border-radius: 999px; font-size: 12.5px; font-weight: 600; }
  .grid { display: grid; grid-template-columns: 1fr 1fr; gap: 12px; }
  footer { margin-top: 40px; font-size: 11.5px; color: #767a88; text-align: center; }
</style>
</head>
<body>
  <div class="sheet">
    <div class="brand">Resume<b>AI</b></div>
    <h1>${escapeHtml(analysis.filename)}</h1>
    <div class="meta">${escapeHtml(analysis.candidateName)} · ${escapeHtml(analysis.targetTitle)} · ${date}</div>
    <div class="score">${analysis.atsScore}<span class="suffix"> / 100</span></div>
    <div class="meta">Overall ATS score — ${scoreLabelFor(analysis.atsScore)}</div>

    <h2>Score breakdown</h2>
    <ul>${analysis.breakdown.map((b) => `<li>${b.category}: <b>${b.score}/100</b></li>`).join("")}</ul>

    <h2>Insights</h2>
    <ul>${analysis.insights.map((i) => `<li><b>${escapeHtml(i.title)}</b>${escapeHtml(i.description)}</li>`).join("")}</ul>

    <h2>Skill match</h2>
    <div><b style="font-size:13px">Matched (${analysis.jobMatch.matchedSkills.length})</b><br>${analysis.jobMatch.matchedSkills.slice(0, 12).map((s) => `<span class="pill">${escapeHtml(s)}</span>`).join("") || "<em>none</em>"}</div>
    <div style="margin-top:12px"><b style="font-size:13px">Missing (${analysis.jobMatch.missingSkills.length})</b><br>${analysis.jobMatch.missingSkills.map((s) => `<span class="pill">${escapeHtml(s)}</span>`).join("") || "<em>none</em>"}</div>

    <h2>Section analysis</h2>
    <div class="grid">${analysis.sections.map((s) => `<li><b>${escapeHtml(s.label)} — ${s.score}/100</b>${escapeHtml(s.present ? "Section detected" : "Section missing")}</li>`).join("")}</div>

    <h2>Action plan</h2>
    <ul>${analysis.actionPlan.map((a) => `<li><b>${String(a.step).padStart(2, "0")}. ${escapeHtml(a.title)}</b>${escapeHtml(a.description)}</li>`).join("")}</ul>

    <footer>Generated by ResumeAI · Files are processed locally and never stored.</footer>
  </div>
</body>
</html>`;

  const blob = new Blob([html], { type: "text/html" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${analysis.filename.replace(/\.(pdf|docx?)$/i, "")}-resumeai-report.html`;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

function scoreLabelFor(score: number): string {
  if (score >= 90) return "Excellent Match";
  if (score >= 78) return "Strong Match";
  if (score >= 62) return "Good Match";
  if (score >= 45) return "Moderate Match";
  return "Needs Work";
}

function escapeHtml(s: string): string {
  return s.replace(/[&<>"']/g, (c) => `&#${c.charCodeAt(0)};`);
}